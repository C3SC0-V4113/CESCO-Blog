import { z } from 'zod';

import { contentDocSchema, type ContentDoc } from '@/lib/content/schema';
const draftContentSchema = contentDocSchema.refine((doc) =>
  doc.content.every(
    (node) =>
      node.type !== 'image' &&
      (node.type !== 'heading' || node.attrs.level === 2 || node.attrs.level === 3)
  )
);

/**
 * The editor offers only h2 and h3. Published content may retain any heading
 * level, so normalize it only when that content is loaded for editing.
 */
export function normalizeContentForDraft(content: ContentDoc): ContentDoc {
  return {
    ...content,
    content: content.content.map((node) => {
      if (node.type !== 'heading') return node;
      const level = node.attrs.level === 1 ? 2 : node.attrs.level >= 4 ? 3 : node.attrs.level;
      return { ...node, attrs: { ...node.attrs, level } };
    }),
  };
}

export const saveDraftSchema = z.strictObject({
  postId: z.string().min(1),
  localizationId: z.string().min(1),
  draftToken: z.string().nullable(),
  // Generated by the client per attempt, so a retry can prove it is the attempt
  // that already landed (ADR-0035).
  nextToken: z.uuid(),
  title: z.string().max(300),
  excerpt: z.string().max(1000).nullable(),
  contentJson: draftContentSchema,
});
export type SaveDraftInput = z.infer<typeof saveDraftSchema>;
export type EditorDraft = Omit<SaveDraftInput, 'postId' | 'localizationId' | 'nextToken'> & {
  seoTitle?: string | null;
  seoDescription?: string | null;
  canonicalUrl?: string | null;
  ogTitle?: string | null;
  ogDescription?: string | null;
  ogImageMediaId?: string | null;
  ogImageAlt?: string | null;
};
export type EditorLocalizations = Partial<Record<'es' | 'en', string>>;

// Checks editor output against the contract the server enforces, so an edit it
// would reject is caught before it is queued. Issues name a path and a code
// only: they end up in the console, and the document text must not.
export function parseDraftContent(
  value: unknown
): { success: true; data: ContentDoc } | { success: false; issues: string[] } {
  const result = draftContentSchema.safeParse(value);
  if (result.success) return { success: true, data: result.data };
  return {
    success: false,
    issues: result.error.issues.map(
      ({ path, code }) => `${['doc', ...path.map(String)].join('.')}: ${code}`
    ),
  };
}
